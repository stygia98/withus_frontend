const START_C = 105;
const STOP = "2331112"; // 끝 기호는 막대가 하나 더 있어 7개, 합 13

/** 짝수 자리 숫자를 C 세트 기호 값으로 (검사 기호 포함, 시작·끝 제외) */
export function code128cValues(digits: string): number[] {
  if (!/^(\d\d)+$/.test(digits)) {
    throw new Error("Code128C 는 짝수 자리 숫자만 담는다");
  }
  const data: number[] = [];
  for (let i = 0; i < digits.length; i += 2) data.push(Number(digits.slice(i, i + 2)));
  const check = data.reduce((sum, v, i) => sum + v * (i + 1), START_C) % 103;
  return [...data, check];
}

/**
 * 막대·빈칸 너비 배열 (모듈 단위, 막대부터 번갈아). 앞뒤 조용한 영역(quiet zone)은 넣지 않는다 —
 * 그리는 쪽에서 양옆에 10모듈 이상 여백을 둔다.
 */
export function code128cWidths(digits: string): number[] {
  const symbols = [PATTERNS[START_C], ...code128cValues(digits).map((v) => PATTERNS[v]), STOP];
  return symbols.join("").split("").map(Number);
}
